from zipgive_data.irs import parse_bmf

SAMPLE = """EIN,NAME,ICO,STREET,CITY,STATE,ZIP,GROUP,SUBSECTION,AFFILIATION,CLASSIFICATION,RULING,DEDUCTIBILITY,FOUNDATION,ACTIVITY,ORGANIZATION,STATUS,TAX_PERIOD,ASSET_CD,INCOME_CD,FILING_REQ_CD,PF_FILING_REQ_CD,ACCT_PD,ASSET_AMT,INCOME_AMT,REVENUE_AMT,NTEE_CD,SORT_NAME
010123456,MILLBROOK CHILDRENS FUND,,1 MAIN ST,MILLBROOK,NY,12545-0001,0000,03,3,1000,201001,1,15,000000000,1,01,202312,3,3,01,0,12,250000,120000,110000,P30,
020654321,DOVER PLAINS ROD AND GUN CLUB,,2 ELM ST,DOVER PLAINS,NY,12522,0000,07,3,1000,199001,2,00,000000000,1,01,202312,1,1,02,0,12,1000,500,500,N60,
"""


def test_parse_keeps_501c3_only():
    rows = parse_bmf(SAMPLE)
    assert len(rows) == 1
    r = rows[0]
    assert r["ein"] == "010123456" and r["subsection"] == "03" and r["deductibility"] == "1"
    assert r["state"] == "NY" and r["revenue_amt"] == 110000 and r["ntee_cd"] == "P30"


def test_parse_all():
    assert len(parse_bmf(SAMPLE, only_501c3=False)) == 2
